"""Tests for scripts/dependency_floors.py (issue 187): no known-vulnerable version of a triaged dependency may come back.
The npm check reads firebase/package-lock.json, the Gradle check reads gradle/verification-metadata.xml (Gradle fails the build for an
artifact that has no entry there, so the file lists exactly what resolves). Each rule has a negative case (vulnerable version is flagged,
also at the range edge and nested in node_modules) and a positive case (patched version, unrelated package, pom-only entry pass).
Run: python3 -I scripts/test_dependency_floors.py"""

import importlib
import json
import os
import re
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
sys.path.insert(0, HERE)

df = importlib.import_module("dependency_floors")

# Every package of the 14 Dependabot alerts open at main a877576 (issue 187), by ecosystem. Each needs a rule.
ALERT_NPM = {"@grpc/grpc-js", "minimatch", "uuid"}
ALERT_GRADLE = {
    "com.google.guava:guava", "org.freemarker:freemarker", "org.bouncycastle:bcprov-jdk18on", "org.bouncycastle:bcpkix-jdk18on",
    "org.codehaus.plexus:plexus-utils", "org.bitbucket.b_c:jose4j", "org.jdom:jdom2", "org.apache.commons:commons-lang3",
    "org.apache.httpcomponents:httpclient",
}


def lock(**versions):
    """A package-lock.json text with one top-level package per name=version (a key with `/` in the name uses `__`)."""
    pkgs = {"": {"name": "x"}}
    for name, version in versions.items():
        pkgs[f"node_modules/{name.replace('__', '/')}"] = {"version": version, "dev": True}
    return json.dumps({"lockfileVersion": 3, "packages": pkgs})


def meta(*components):
    """A verification-metadata.xml text; a component is (group, name, version, artifact suffixes)."""
    body = ""
    for group, name, version, suffixes in components:
        arts = "".join(
            f'<artifact name="{name}-{version}.{s}"><sha256 value="{"0" * 64}" origin="Generated by Gradle"/></artifact>' for s in suffixes
        )
        body += f'<component group="{group}" name="{name}" version="{version}">{arts}</component>'
    return f'<?xml version="1.0"?><verification-metadata xmlns="https://schema.gradle.org/dependency-verification"><components>{body}</components></verification-metadata>'


class NpmRules(unittest.TestCase):
    def flagged(self, **v):
        return df.check_npm_lock(lock(**v))

    def test_vulnerable_grpc_flagged(self):
        problems = self.flagged(**{"@grpc__grpc-js": "1.9.16"})
        self.assertEqual(len(problems), 1)
        self.assertIn("@grpc/grpc-js 1.9.16", problems[0])
        self.assertIn("1.13.6", problems[0])

    def test_patched_grpc_passes(self):
        self.assertEqual(self.flagged(**{"@grpc__grpc-js": "1.14.7"}), [])
        self.assertEqual(self.flagged(**{"@grpc__grpc-js": "1.13.6"}), [])
        self.assertEqual(self.flagged(**{"@grpc__grpc-js": "1.13.5"}) != [], True)

    def test_minimatch_range_edges(self):
        for bad in ("7.0.0", "9.0.9", "10.2.6", "11.0.0"):
            self.assertEqual(len(self.flagged(minimatch=bad)), 1, bad)
        for ok in ("3.1.5", "5.1.9", "6.2.3", "11.0.1", "11.0.8"):
            self.assertEqual(self.flagged(minimatch=ok), [], ok)

    def test_uuid(self):
        self.assertEqual(len(self.flagged(uuid="9.0.1")), 1)
        self.assertEqual(self.flagged(uuid="11.1.1"), [])

    def test_grpc_1_14_line_range_edges(self):
        # GHSA-m9gg-hp2v-232j and GHSA-f596-whhp-79r4 also cover >=1.14.0 <1.14.5 (R1-01).
        for bad in ("1.14.0", "1.14.3", "1.14.4"):
            problems = self.flagged(**{"@grpc__grpc-js": bad})
            self.assertEqual(len(problems), 1, bad)
            self.assertIn("1.14.5", problems[0])
        for ok in ("1.13.6", "1.13.9", "1.14.5", "1.14.7", "1.15.0"):
            self.assertEqual(self.flagged(**{"@grpc__grpc-js": ok}), [], ok)

    def test_uuid_12_and_13_ranges(self):
        # GHSA-w5hq-g745-h8pq also covers >=12.0.0 <12.0.1 and >=13.0.0 <13.0.1 (R1-01).
        for bad, fixed in (("12.0.0", "12.0.1"), ("13.0.0", "13.0.1")):
            problems = self.flagged(uuid=bad)
            self.assertEqual(len(problems), 1, bad)
            self.assertIn(fixed, problems[0])
        for ok in ("11.1.1", "11.2.0", "12.0.1", "12.1.0", "13.0.1", "14.0.3"):
            self.assertEqual(self.flagged(uuid=ok), [], ok)
        self.assertEqual(len(self.flagged(uuid="11.1.0")), 1)

    def test_one_package_can_be_flagged_once_per_copy_not_once_per_range(self):
        problems = self.flagged(uuid="12.0.0")
        self.assertEqual(len(problems), 1)

    def test_nested_package_is_found(self):
        text = json.dumps({"packages": {"": {}, "node_modules/a/node_modules/uuid": {"version": "9.0.1"}}})
        self.assertEqual(len(df.check_npm_lock(text)), 1)

    def test_unrelated_package_and_similar_name_pass(self):
        self.assertEqual(self.flagged(uuidx="1.0.0", **{"minimatch-cli": "1.0.0"}), [])

    def test_every_vulnerable_copy_is_reported(self):
        text = json.dumps({"packages": {"": {}, "node_modules/uuid": {"version": "9.0.1"}, "node_modules/b/node_modules/uuid": {"version": "8.3.2"}}})
        self.assertEqual(len(df.check_npm_lock(text)), 2)

    def test_malformed_lock_is_a_problem_not_a_crash(self):
        self.assertTrue(df.check_npm_lock("{not json"))
        self.assertTrue(df.check_npm_lock("{}"))  # no packages section: the check would pass vacuously


class GradleRules(unittest.TestCase):
    def flagged(self, *components):
        return df.check_gradle_metadata(meta(*components))

    def test_vulnerable_jar_flagged(self):
        problems = self.flagged(("org.bouncycastle", "bcprov-jdk18on", "1.80.2", ["jar", "pom"]))
        self.assertEqual(len(problems), 1)
        self.assertIn("org.bouncycastle:bcprov-jdk18on 1.80.2", problems[0])
        self.assertIn("1.85", problems[0])

    def test_aar_counts_as_used(self):
        self.assertEqual(len(self.flagged(("org.freemarker", "freemarker", "2.3.32", ["aar"]))), 1)

    def test_patched_versions_pass(self):
        ok = [
            ("org.bouncycastle", "bcprov-jdk18on", "1.85", ["jar", "pom"]),
            ("com.google.guava", "guava", "33.7.2-jre", ["jar", "pom"]),
            ("org.apache.commons", "commons-lang3", "3.18.0", ["jar", "pom"]),
            ("org.apache.httpcomponents", "httpclient", "4.5.14", ["jar", "pom"]),
        ]
        self.assertEqual(self.flagged(*ok), [])

    def test_guava_just_below_the_fix_is_flagged(self):
        self.assertEqual(len(self.flagged(("com.google.guava", "guava", "33.7.1-jre", ["jar"]))), 1)
        self.assertEqual(len(self.flagged(("com.google.guava", "guava", "33.4.0-jre", ["jar"]))), 1)

    def test_plexus_utils_4_0_range_edges(self):
        # GHSA-6fmv-xxpf-w3cw also covers >=4.0.0 <4.0.3 (R1-01).
        for bad in ("3.6.0", "4.0.0", "4.0.2"):
            problems = self.flagged(("org.codehaus.plexus", "plexus-utils", bad, ["jar", "pom"]))
            self.assertEqual(len(problems), 1, bad)
        self.assertIn("4.0.3", self.flagged(("org.codehaus.plexus", "plexus-utils", "4.0.1", ["jar"]))[0])
        for ok in ("3.6.1", "3.9.0", "4.0.3", "4.1.0"):
            self.assertEqual(self.flagged(("org.codehaus.plexus", "plexus-utils", ok, ["jar", "pom"])), [], ok)

    def test_pom_only_entry_is_not_a_used_artifact(self):
        self.assertEqual(self.flagged(("org.jdom", "jdom2", "2.0.6", ["pom"])), [])

    def test_module_metadata_only_is_not_a_used_artifact(self):
        self.assertEqual(self.flagged(("org.jdom", "jdom2", "2.0.6", ["module", "pom"])), [])

    def test_similar_names_pass(self):
        parent = ("com.google.guava", "guava-parent", "26.0-android", ["pom"])
        self.assertEqual(self.flagged(parent, ("com.google.guava", "failureaccess", "1.0.2", ["jar"])), [])
        self.assertEqual(self.flagged(("org.bouncycastle", "bcutil-jdk18on", "1.80.2", ["jar"])), [])

    def test_other_group_same_name_passes(self):
        self.assertEqual(self.flagged(("example", "guava", "1.0", ["jar"])), [])

    def test_malformed_metadata_is_a_problem(self):
        self.assertTrue(df.check_gradle_metadata("<not xml"))
        self.assertTrue(df.check_gradle_metadata(meta()))  # no components: would pass vacuously


class RuleTable(unittest.TestCase):
    def test_every_alert_package_has_a_rule(self):
        self.assertEqual({r.name for r in df.RULES if r.ecosystem == "npm"} >= ALERT_NPM, True)
        self.assertEqual({r.name for r in df.RULES if r.ecosystem == "gradle"} >= ALERT_GRADLE, True)

    def test_every_rule_names_its_advisory_and_its_ranges(self):
        for r in df.RULES:
            self.assertRegex(r.advisory, r"^GHSA-[2-9a-z]{4}-[2-9a-z]{4}-[2-9a-z]{4}$", r.name)
            self.assertTrue(r.ranges, r.name)
            for lo, hi in r.ranges:
                self.assertRegex(lo, r"^[0-9]+(\.[0-9]+)*$", r.name)
                self.assertRegex(hi, r"^[0-9]+(\.[0-9]+)+$", r.name)

    def test_ranges_are_ordered_and_disjoint(self):
        for r in df.RULES:
            keys = [(df.version_key(lo), df.version_key(hi)) for lo, hi in r.ranges]
            for lo, hi in keys:
                self.assertLess(lo, hi, r.name)
            for (_, prev_hi), (next_lo, _) in zip(keys, keys[1:], strict=False):
                self.assertLessEqual(prev_hi, next_lo, r.name)

    def test_multi_range_advisories_are_modelled(self):
        by_name = {(r.ecosystem, r.name): r for r in df.RULES}
        self.assertEqual(len(by_name[("npm", "uuid")].ranges), 3)
        self.assertEqual(len(by_name[("npm", "@grpc/grpc-js")].ranges), 2)
        self.assertEqual(len(by_name[("gradle", "org.codehaus.plexus:plexus-utils")].ranges), 2)

    def test_version_ordering(self):
        self.assertTrue(df.version_key("1.13.10") > df.version_key("1.13.6"))
        self.assertTrue(df.version_key("2.0.6.1") > df.version_key("2.0.6"))
        self.assertTrue(df.version_key("33.7.2-jre") > df.version_key("33.7.1-jre"))
        self.assertTrue(df.version_key("11.0.8") > df.version_key("11.0.1"))


class Repo(unittest.TestCase):
    def test_repo_has_no_vulnerable_versions(self):
        r = subprocess.run([sys.executable, "-I", os.path.join(HERE, "dependency_floors.py"), ROOT], capture_output=True, text=True)
        self.assertEqual((r.returncode, r.stdout), (0, ""), r.stdout)

    def test_missing_file_fails_with_a_message(self):
        with tempfile.TemporaryDirectory() as d:
            r = subprocess.run([sys.executable, "-I", os.path.join(HERE, "dependency_floors.py"), d], capture_output=True, text=True)
            self.assertEqual(r.returncode, 1)
            self.assertIn("package-lock.json", r.stdout)

    def test_script_fails_on_a_vulnerable_fixture(self):
        with tempfile.TemporaryDirectory() as d:
            os.makedirs(os.path.join(d, "firebase"))
            os.makedirs(os.path.join(d, "gradle"))
            with open(os.path.join(d, "firebase", "package-lock.json"), "w", encoding="utf-8") as f:
                f.write(lock(uuid="9.0.1"))
            with open(os.path.join(d, "gradle", "verification-metadata.xml"), "w", encoding="utf-8") as f:
                f.write(meta(("org.freemarker", "freemarker", "2.3.32", ["jar"])))
            r = subprocess.run([sys.executable, "-I", os.path.join(HERE, "dependency_floors.py"), d], capture_output=True, text=True)
            self.assertEqual(r.returncode, 1)
            self.assertIn("uuid 9.0.1", r.stdout)
            self.assertIn("freemarker 2.3.32", r.stdout)


class Wiring(unittest.TestCase):
    def test_verify_sh_runs_tests_then_the_check(self):
        with open(os.path.join(ROOT, "scripts", "verify.sh"), encoding="utf-8") as f:
            text = f.read()
        tests = "step dependency-floors-tests python3 -I scripts/test_dependency_floors.py"
        check = "step dependency-floors python3 -I scripts/dependency_floors.py"
        self.assertIn(tests, text)
        self.assertIn(check, text)
        self.assertLess(text.index(tests), text.index(check))
        self.assertIsNone(re.search(r"^\s*#.*dependency-floors", text, re.M))


if __name__ == "__main__":
    unittest.main()
