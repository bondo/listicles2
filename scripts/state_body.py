#!/usr/bin/env python3
"""State issue body (M1-77, owner decision 7076085601 item 2): validate its JSON block and render the summary above it.

The body is free prose (kept as is), a generated summary between the markers BEGIN and END, and exactly one fenced
```json block that holds the state: usage, sessions, branches, triggers, the owner queue and the next steps. The block
is the source; the summary is derived from it, so edit the block and run `render`. Standard library only.

Usage:
  scripts/state_body.py validate BODY   exit 1 with every problem on stderr; BODY is a file or - for stdin
  scripts/state_body.py render BODY     print the body with the summary regenerated and the block in canonical form

Read the body with: gh api repos/bondo/listicles2/issues/15 --jq .body > state.md
scripts/tasks.py --state state.md reads the claimed and in-review task ids from the same block.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime
from collections.abc import Callable
from pathlib import Path
from typing import Any

BEGIN = "<!-- state:summary: generated by scripts/state_body.py render from the JSON block below; edit the block -->"
END = "<!-- /state:summary -->"
FENCE_OPEN, FENCE_CLOSE = "```json", "```"
SCHEMA = 1

Check = Callable[[Any, str, list[str]], None]


class StateError(Exception):
    def __init__(self, errors: list[str]):
        super().__init__("\n".join(errors))
        self.errors = errors


def kind(ok: Callable[[Any], bool], what: str) -> Check:
    def check(v: Any, path: str, errs: list[str]) -> None:
        if not ok(v):
            errs.append(f"{path}: expected {what}, got {json.dumps(v)[:60]}")
    return check


def pattern(rx: str, what: str) -> Check:
    return kind(lambda v: isinstance(v, str) and re.fullmatch(rx, v, re.ASCII) is not None, what)


def one_of(*values: str) -> Check:
    return kind(lambda v: v in values, "one of " + ", ".join(values))


def nullable(inner: Check) -> Check:
    def check(v: Any, path: str, errs: list[str]) -> None:
        if v is not None:
            inner(v, path, errs)
    return check


def list_of(inner: Check, lo: int = 0, hi: int | None = None) -> Check:
    def check(v: Any, path: str, errs: list[str]) -> None:
        if not isinstance(v, list):
            errs.append(f"{path}: expected a list, got {json.dumps(v)[:60]}")
            return
        if len(v) < lo or (hi is not None and len(v) > hi):
            errs.append(f"{path}: expected {lo} to {hi if hi is not None else 'any number of'} items, got {len(v)}")
        for i, item in enumerate(v):
            inner(item, f"{path}[{i}]", errs)
    return check


def obj(fields: dict[str, Check], optional: frozenset[str] = frozenset()) -> Check:
    def check(v: Any, path: str, errs: list[str]) -> None:
        where = f"{path}: " if path else ""
        if not isinstance(v, dict):
            errs.append(f"{where}expected an object, got {json.dumps(v)[:60]}")
            return
        errs.extend(f"{where}unknown field {k!r}" for k in v if k not in fields)
        errs.extend(f"{where}missing field {k!r}" for k in fields if k not in v and k not in optional)
        for k, c in fields.items():
            if k in v:
                c(v[k], f"{path}.{k}" if path else k, errs)
    return check


TEXT = kind(lambda v: isinstance(v, str) and v.strip() != "" and not set(v) & {"\n", "\r"}, "a non-empty string on one line")
COUNT = kind(lambda v: type(v) is int and v >= 0, "a whole number >= 0")
NUMBER = kind(lambda v: type(v) is int and v > 0, "a PR or issue number")
def is_time(v: Any) -> bool:
    if not isinstance(v, str) or not re.fullmatch(r"\d{4}-\d\d-\d\dT\d\d:\d\d(:\d\d)?Z", v, re.ASCII):
        return False
    try:
        datetime.strptime(v, "%Y-%m-%dT%H:%M:%SZ" if v.count(":") == 2 else "%Y-%m-%dT%H:%MZ")
    except ValueError:
        return False
    return True


TIME = kind(is_time, "a UTC time like 2026-11-23T05:33Z")
SESSION = pattern(r"session_[A-Za-z0-9]+", "a session id")
TASK = pattern(r"M\d+(\.\d+)?-(\d\d|O\d+|FU)", "a task id")
SHA = pattern(r"[0-9a-f]{7,40}", "a commit SHA")
ROLE = pattern(r"[a-z][a-z-]*", "a role (lower case, e.g. implementer)")
USAGE_RX = r"ok|near limit \((5-hour(, forecast|, rateLimitType unknown)?|7-day|overage)\)|paused until (?P<hhmm>\d\d:\d\d) UTC"


def is_usage(v: Any) -> bool:
    m = re.fullmatch(USAGE_RX, v, re.ASCII) if isinstance(v, str) else None
    if m is None:
        return False
    try:
        return m["hhmm"] is None or bool(datetime.strptime(m["hhmm"], "%H:%M"))
    except ValueError:
        return False


USAGE = kind(is_usage, "one of the ORCHESTRATION.md 3.1 usage states")
STATUSES = ("running", "idle-with-result", "idle-no-result", "failed", "archived", "interrupted (usage)")

TAG = pattern(r"[a-z][a-z-]*:\S+", "a session tag like pr:319 (ORCHESTRATION.md 2.1)")

SESSION_ROW = obj({"id": SESSION, "role": ROLE, "tags": list_of(TAG), "branch": nullable(TEXT), "pr": nullable(NUMBER), "tasks": list_of(TASK),
                   "spawned": TIME, "expects": TEXT, "checked": TIME, "status": one_of(*STATUSES), "note": TEXT},
                  optional=frozenset({"note"}))
BRANCH_ROW = obj({"name": TEXT, "holder": nullable(SESSION), "pr": nullable(NUMBER), "in_review": list_of(TASK),
                  "reviewed_through": nullable(SHA), "unreviewed_since": nullable(SHA), "disposition": TEXT})
STATE = obj({
    "schema": kind(lambda v: type(v) is int and v == SCHEMA, str(SCHEMA)),
    "orchestrator": obj({"session": SESSION, "since": TIME, "predecessor": nullable(SESSION), "depth": COUNT}),
    "updated": obj({"at": TIME, "after": TEXT}),
    "inbox_since": TIME,
    "tasks_ref": TEXT,
    "usage": obj({"state": USAGE, "read_at": TIME}),
    "sessions": list_of(SESSION_ROW),
    "branches": list_of(BRANCH_ROW),
    "triggers": list_of(obj({"id": pattern(r"trig_[A-Za-z0-9]+", "a trigger id"), "fires_into": SESSION, "purpose": TEXT,
                             "next_run": nullable(TIME)})),
    "subscriptions": list_of(NUMBER),
    "owner_queue": list_of(obj({"kind": one_of("todo", "question", "approval"), "task": nullable(TASK),
                                "issue": nullable(NUMBER), "text": TEXT, "then": TEXT})),
    "follow_ups": obj({k: COUNT for k in ("open", "blocker", "major", "minor", "nit")}),
    "next": list_of(TEXT, 1, 3),
    "decisions": list_of(obj({"comment": NUMBER, "what": TEXT})),
})


def cross_checks(data: dict) -> list[str]:
    """Rules across rows; only called once the shape is valid."""
    errs = []
    for key, label, name in (("sessions", "session", "id"), ("branches", "branch", "name")):
        seen = [row[name] for row in data[key]]
        errs += [f"duplicate {label} {x}" for x in sorted({x for x in seen if seen.count(x) > 1})]
    for key, ids in (("sessions", "tasks"), ("branches", "in_review")):
        for i, row in enumerate(data[key]):
            errs += [f"{key}[{i}]: {t} listed twice" for t in sorted({t for t in row[ids] if row[ids].count(t) > 1})]
    claims = [t for row in data["sessions"] for t in set(row["tasks"])]
    errs += [f"{t} is claimed by {claims.count(t)} sessions" for t in sorted({t for t in claims if claims.count(t) > 1})]
    for i, row in enumerate(data["sessions"]):
        if row["status"] in ("archived", "failed") and row["tasks"]:
            errs.append(f"sessions[{i}]: {row['status']} but still claims {', '.join(row['tasks'])} (release the claim)")
    fu = data["follow_ups"]
    total = sum(fu[k] for k in ("blocker", "major", "minor", "nit"))
    if fu["open"] != total:
        errs.append(f"follow_ups.open: {fu['open']} is not the sum of the severities ({total})")
    return errs


def no_duplicate_keys(pairs: list[tuple[str, Any]]) -> dict:
    keys = [k for k, _ in pairs]
    dup = sorted({k for k in keys if keys.count(k) > 1})
    if dup:
        raise ValueError(f"duplicate key {dup[0]!r}")
    return dict(pairs)


def find_block(lines: list[str]) -> tuple[int, int]:
    """Line indexes of the opening and closing fence of the one ```json block."""
    opens = [i for i, ln in enumerate(lines) if ln.rstrip(" \t") == FENCE_OPEN]
    if not opens:
        raise StateError([f"no {FENCE_OPEN} block in the body"])
    if len(opens) > 1:
        raise StateError([f"{len(opens)} {FENCE_OPEN} blocks in the body; exactly one holds the state"])
    close = next((i for i in range(opens[0] + 1, len(lines)) if lines[i].rstrip(" \t") == FENCE_CLOSE), None)
    if close is None:
        raise StateError([f"the {FENCE_OPEN} block is not closed with {FENCE_CLOSE}"])
    return opens[0], close


def parse(text: str) -> tuple[list[str], int, int, dict]:
    if not text.strip():
        raise StateError(["the body is empty (a failed gh call?); refusing to read it as no state"])
    lines = re.split(r"\r\n|\r|\n", text)  # CommonMark line ends only, not str.splitlines()' U+2028, U+0085 (R1-01)
    while lines[-1] == "":
        lines.pop()  # the final line end opens no further line and trailing blank lines are noise; render() adds one newline
    start, end = find_block(lines)
    marks = [ln.strip() for ln in lines if ln.strip() in (BEGIN, END)]
    if marks not in ([], [BEGIN, END]):
        raise StateError(["summary markers: need both, once each, in order, or neither"])
    try:
        data = json.loads("\n".join(lines[start + 1:end]), object_pairs_hook=no_duplicate_keys)
    except ValueError as e:
        raise StateError([f"malformed JSON in the state block: {e}"]) from None
    if not isinstance(data, dict):
        raise StateError(["the state block must be a JSON object"])
    errs: list[str] = []
    STATE(data, "", errs)
    if errs:
        raise StateError(errs)
    errs = cross_checks(data)
    if errs:
        raise StateError(errs)
    return lines, start, end, data


def load(text: str) -> dict:
    """The validated state; raises StateError with every problem found."""
    return parse(text)[3]


def dump(data: dict) -> str:
    """Canonical block content: one top-level key per line, one list item per line."""
    rows = []
    for k, v in data.items():
        if isinstance(v, list) and v:
            items = ",\n".join("    " + json.dumps(x, ensure_ascii=False) for x in v)
            rows.append(f"  {json.dumps(k)}: [\n{items}\n  ]")
        else:
            rows.append(f"  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}")
    return "{\n" + ",\n".join(rows) + "\n}"


def summary(d: dict) -> str:
    o, fu = d["orchestrator"], d["follow_ups"]
    pred = f"`{o['predecessor']}`" if o["predecessor"] else "none"
    out = [
        f"**Orchestrator:** `{o['session']}` since {o['since']} · predecessor {pred} · lineage depth {o['depth']}",
        f"**Updated:** {d['updated']['at']}, after {d['updated']['after']}",
        f"**Inbox since:** {d['inbox_since']} · **Tasks ref:** `{d['tasks_ref']}`",
        f"**Usage:** {d['usage']['state']} (read {d['usage']['read_at']})",
        f"**Follow-ups:** open follow-ups: {fu['open']} (blocker {fu['blocker']}, major {fu['major']}, "
        f"minor {fu['minor']}, nit {fu['nit']})",
        "", "**Next**", *(f"{i}. {step}" for i, step in enumerate(d["next"], 1)),
        "", f"**Owner queue** ({len(d['owner_queue'])})",
    ]
    for q in d["owner_queue"]:
        ref = " ".join(x for x in (q["task"], f"#{q['issue']}" if q["issue"] else None) if x)
        out.append(f"- {q['kind']}{' ' + ref if ref else ''}: {q['text']}; then {q['then']}")
    out.append(f"\n**Sessions** ({len(d['sessions'])})")
    for s in d["sessions"]:
        where = ", ".join(x for x in (f"`{s['branch']}`" if s["branch"] else None, f"PR #{s['pr']}" if s["pr"] else None,
                                       "claims " + ",".join(s["tasks"]) if s["tasks"] else None) if x)
        note = f". {s['note']}" if "note" in s else ""
        out.append(f"- `{s['id']}` {s['role']}{', ' + where if where else ''}: {s['status']} (checked {s['checked']}){note}")
    out.append(f"\n**Branches** ({len(d['branches'])})")
    for b in d["branches"]:
        bits = [f"PR #{b['pr']}" if b["pr"] else None, f"holder `{b['holder']}`" if b["holder"] else "no holder",
                "in review " + ",".join(b["in_review"]) if b["in_review"] else None,
                f"reviewed through `{b['reviewed_through']}`" if b["reviewed_through"] else None,
                f"unreviewed since `{b['unreviewed_since']}`" if b["unreviewed_since"] else None]
        out.append(f"- `{b['name']}` {', '.join(x for x in bits if x)}: {b['disposition']}")
    out.append("\n**Scheduled tasks:** " + ("; ".join(f"`{t['id']}` into `{t['fires_into']}`, {t['purpose']}, next {t['next_run']}"
                                                      for t in d["triggers"]) or "none"))
    out.append("**PR subscriptions:** " + (", ".join(f"#{n}" for n in d["subscriptions"]) or "none"))
    out.append("**Standing owner decisions:** " + ("; ".join(f"{x['comment']} ({x['what']})" for x in d["decisions"]) or "none"))
    return "\n".join(out)


def render(text: str) -> str:
    """The body with the summary regenerated above the block and the block in canonical form."""
    lines, start, end, data = parse(text)
    region = [BEGIN, summary(data), END, ""]
    block = [FENCE_OPEN, dump(data), FENCE_CLOSE]
    stripped = [ln.strip() for ln in lines]
    if BEGIN in stripped:
        b, e = stripped.index(BEGIN), stripped.index(END)
        if not b < e < start:
            raise StateError(["summary markers: the summary must sit above the JSON block"])
        head, middle = lines[:b], lines[e + 1:start]
        while middle and not middle[0].strip():
            middle = middle[1:]
    else:
        head, middle = lines[:start], []
    return "\n".join(head + region + middle + block + lines[end + 1:]) + "\n"


def read(path: str) -> str:
    if path == "-":
        return sys.stdin.read()
    try:
        return Path(path).read_text(encoding="utf-8")
    except OSError as e:
        raise StateError([f"cannot read {path}: {e.strerror}"]) from None
    except UnicodeDecodeError:
        raise StateError([f"cannot read {path}: not UTF-8"]) from None


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("command", choices=("validate", "render"))
    ap.add_argument("body", help="the state issue body (a file, or - for stdin)")
    a = ap.parse_args(argv)
    try:
        text = read(a.body)
        if a.command == "render":
            sys.stdout.write(render(text))
            return 0
        d = load(text)
    except StateError as e:
        for msg in e.errors:
            print(f"error: {msg}", file=sys.stderr)
        return 1
    claimed = sum(len(s["tasks"]) for s in d["sessions"])
    in_review = sum(len(b["in_review"]) for b in d["branches"])
    print(f"ok: {len(d['sessions'])} sessions, {len(d['branches'])} branches, {claimed} claimed, {in_review} in review")
    return 0


if __name__ == "__main__":
    sys.exit(main())
